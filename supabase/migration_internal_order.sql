-- ============================================================================
--  每日菜單合併店家改名：將既有的「每日菜單」店家更名為「內訂」
--  在 Supabase SQL Editor 執行一次即可（可重複執行）。
--  說明：每日菜單功能會把各廠商的每月菜單整合到單一店家「內訂」，
--       品項名稱格式為「廠商-餐點」（例如：正園-B餐）。
-- ============================================================================

-- 若「內訂」店家已存在，先刪除（避免名稱衝突；通常不會發生）
-- 注意：此處不刪除，僅在有「每日菜單」時改名。
update public.stores
   set name = '內訂'
 where name = '每日菜單'
   and is_deleted = false;
